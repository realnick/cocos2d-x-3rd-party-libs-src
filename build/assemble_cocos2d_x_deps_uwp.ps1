#Requires -Version 5.0
<#
Copies vcpkg-installed artifacts for a given UWP triplet (arm64-uwp,
arm-uwp, x64-uwp, x86-uwp) into the cocos2d-x-deps directory layout
that cocos2d-x consumes at build time.

Note: names follow the modern vcpkg outputs (e.g. libcrypto-3-arm64.dll,
z.dll) rather than the old cocos2d-x-deps names (libeay32.dll, zlib1.dll).
The cocos2d-x side needs project references updated accordingly.
#>
param(
    [Parameter(Mandatory=$true)][string]$VcpkgInstalled,
    [Parameter(Mandatory=$true)][string]$OutDir,
    [Parameter(Mandatory=$true)][string]$Arch,  # win32 / x64 / arm / arm64
    [string]$DownloadCacheDir = ""              # optional; defaults under vcpkg dir
)

$ErrorActionPreference = 'Stop'

function Copy-One([string]$src, [string]$destDir, [switch]$Optional) {
    if (-not (Test-Path -LiteralPath $src)) {
        if (-not $Optional) { Write-Warning "missing: $src" }
        return
    }
    if (-not (Test-Path -LiteralPath $destDir)) {
        New-Item -ItemType Directory -Path $destDir -Force | Out-Null
    }
    Copy-Item -LiteralPath $src -Destination $destDir -Force
}

# Copies every file matching $pattern; used where the exact name carries a
# version or an architecture (libcrypto-3-arm64.dll and friends).
function Copy-Glob([string]$srcDir, [string]$pattern, [string]$destDir) {
    $hits = @(Get-ChildItem -LiteralPath $srcDir -Filter $pattern -File -ErrorAction SilentlyContinue)
    if ($hits.Count -eq 0) {
        Write-Warning "missing: $pattern in $srcDir"
        return
    }
    if (-not (Test-Path -LiteralPath $destDir)) {
        New-Item -ItemType Directory -Path $destDir -Force | Out-Null
    }
    foreach ($h in $hits) { Copy-Item -LiteralPath $h.FullName -Destination $destDir -Force }
}

function Copy-Tree([string]$src, [string]$destDir) {
    if (-not (Test-Path -LiteralPath $src)) {
        Write-Warning "missing tree: $src"
        return
    }
    if (-not (Test-Path -LiteralPath $destDir)) {
        New-Item -ItemType Directory -Path $destDir -Force | Out-Null
    }
    Copy-Item -LiteralPath $src -Destination $destDir -Recurse -Force
}

Write-Host "== assembling cocos2d-x-deps ($Arch) from $VcpkgInstalled =="

# --- headers ------------------------------------------------------------
Copy-Tree "$VcpkgInstalled\include\curl"     "$OutDir\curl\include\win10\"
Copy-Tree "$VcpkgInstalled\include\openssl"  "$OutDir\openssl\include\win10\"

# openssl's configuration.h is generated per architecture -- BN_LLONG /
# THIRTY_TWO_BIT vs SIXTY_FOUR_BIT, and RC4_INT is unsigned char on arm64 and
# unsigned int elsewhere -- so BN_ULONG and RC4_KEY change width with the
# target. cocos2d-x has one include\win10 tree that every architecture compiles
# against, so keep the real headers side by side under canonical arch names and
# leave a dispatching stub where the original was. Without this, two of the
# three architectures disagree with their own prebuilt libraries: harmless while
# callers only pass opaque SSL*/BIO* around, wrong the moment a BN_ULONG or an
# RC4_KEY crosses the boundary.
$osslInc = "$OutDir\openssl\include\win10\openssl"
$canonArch = switch ($Arch) { 'win32' { 'x86' } 'x64' { 'x64' } 'arm64' { 'arm64' } default { $null } }
if ($canonArch -and (Test-Path -LiteralPath "$VcpkgInstalled\include\openssl\configuration.h")) {
    Copy-Item -LiteralPath "$VcpkgInstalled\include\openssl\configuration.h" `
              -Destination "$osslInc\configuration-$canonArch.h" -Force
    $stub = @"
/*
 * Generated by assemble_cocos2d_x_deps_uwp.ps1 -- do not edit.
 *
 * configuration.h is configured per architecture, but cocos2d-x keeps a single
 * include tree for all of them, so the real headers sit next to this one and
 * this picks the matching one at compile time.
 */
#if defined(_M_ARM64) || defined(__aarch64__)
#  include "configuration-arm64.h"
#elif defined(_M_X64) || defined(_M_AMD64) || defined(__x86_64__)
#  include "configuration-x64.h"
#elif defined(_M_IX86) || defined(__i386__)
#  include "configuration-x86.h"
#else
#  error "configuration.h: unsupported architecture"
#endif
"@
    [System.IO.File]::WriteAllText("$osslInc\configuration.h", $stub)
    Write-Host "openssl: configuration.h -> configuration-$canonArch.h plus a per-arch dispatching stub"
}
Copy-Tree "$VcpkgInstalled\include\freetype" "$OutDir\freetype2\include\win10\"
Copy-One  "$VcpkgInstalled\include\ft2build.h" "$OutDir\freetype2\include\win10"
Copy-Tree "$VcpkgInstalled\include\ogg"      "$OutDir\win10-specific\OggDecoder\include\"
Copy-Tree "$VcpkgInstalled\include\vorbis"   "$OutDir\win10-specific\OggDecoder\include\"
Copy-One  "$VcpkgInstalled\include\zconf.h"  "$OutDir\win10-specific\zlib\include"
Copy-One  "$VcpkgInstalled\include\zlib.h"   "$OutDir\win10-specific\zlib\include"

# vcpkg's shared zlib installs a zconf.h whose `#ifdef ZLIB_DLL` guard has been
# rewritten to `#if 1`, so ZEXTERN is unconditionally `extern __declspec(dllimport)`.
# cocos2d-x's external\unzip\unzip.h declares its own functions with ZEXTERN, and
# unzip.cpp then fails with C2491 (definition of dllimport function not allowed).
# cocos2d-x's bundled zconf.h has the `#ifdef ZLIB_DLL` form, so restore it.
$zconf = "$OutDir\win10-specific\zlib\include\zconf.h"
if (Test-Path -LiteralPath $zconf) {
    $text = [System.IO.File]::ReadAllText($zconf)
    # The file has a second `#  if 1` under __BEOS__; keying off the following
    # line picks out the Windows one. \r?\n keeps the file's CRLF endings.
    $pattern     = '(?m)^#  if 1(\r?\n)(#    if defined\(WIN32\))'
    $replacement = '#  ifdef ZLIB_DLL$1$2'
    if ($text -match $pattern) {
        [System.IO.File]::WriteAllText($zconf, [regex]::Replace($text, $pattern, $replacement))
        Write-Host "zconf.h: restored the #ifdef ZLIB_DLL guard (was #if 1)"
    } elseif ($text -notmatch '(?m)^#  ifdef ZLIB_DLL') {
        Write-Warning "zconf.h: ZLIB_DLL guard not in the expected form; external\unzip may hit C2491"
    }
}

# libwebsockets ships several headers at the top of include/.
$lwsHeaders = Get-ChildItem -LiteralPath "$VcpkgInstalled\include" -Filter "libwebsockets*" -ErrorAction SilentlyContinue
foreach ($h in $lwsHeaders) { Copy-Item -LiteralPath $h.FullName -Destination "$OutDir\websockets\include\win10\" -Recurse -Force }
Copy-One "$VcpkgInstalled\include\lws_config.h"      "$OutDir\websockets\include\win10"
# lws_config_priv.h was a libwebsockets 2.x header; 4.x does not install it and
# cocos2d-x does not include it, so its absence is expected.
Copy-One "$VcpkgInstalled\include\lws_config_priv.h" "$OutDir\websockets\include\win10" -Optional

# --- per-arch prebuilt binaries -----------------------------------------
$curl     = "$OutDir\curl\prebuilt\win10\$Arch"
$openssl  = "$OutDir\openssl\prebuilt\win10\$Arch"
$freetype = "$OutDir\freetype2\prebuilt\win10\$Arch"
$sqlite   = "$OutDir\sqlite3\libraries\win10\$Arch"
$ws       = "$OutDir\websockets\prebuilt\win10\$Arch"
$chip     = "$OutDir\chipmunk\prebuilt\win10\$Arch"
$ogg      = "$OutDir\win10-specific\OggDecoder\prebuilt\$Arch"
$zlib     = "$OutDir\win10-specific\zlib\prebuilt\$Arch"

# curl
Copy-One "$VcpkgInstalled\bin\libcurl.dll" $curl
Copy-One "$VcpkgInstalled\lib\libcurl.lib" $curl

# openssl (modern 3.x names - the DLLs carry a version + arch suffix, e.g.
# libcrypto-3-arm64.dll / libcrypto-3-x64.dll, so match them by pattern)
Copy-Glob "$VcpkgInstalled\bin" 'libcrypto-*.dll' $openssl
Copy-Glob "$VcpkgInstalled\bin" 'libssl-*.dll'    $openssl
Copy-One  "$VcpkgInstalled\bin\legacy.dll"        $openssl
Copy-One  "$VcpkgInstalled\lib\libcrypto.lib"     $openssl
Copy-One  "$VcpkgInstalled\lib\libssl.lib"        $openssl

# freetype (+ its transitive DLLs so the freetype shared library resolves)
Copy-One "$VcpkgInstalled\bin\freetype.dll"      $freetype
Copy-One "$VcpkgInstalled\lib\freetype.lib"      $freetype
Copy-One "$VcpkgInstalled\bin\brotlicommon.dll"  $freetype
Copy-One "$VcpkgInstalled\bin\brotlidec.dll"     $freetype
Copy-One "$VcpkgInstalled\bin\brotlienc.dll"     $freetype
Copy-One "$VcpkgInstalled\bin\bz2.dll"           $freetype
Copy-One "$VcpkgInstalled\bin\libpng16.dll"      $freetype

# sqlite3
Copy-One "$VcpkgInstalled\bin\sqlite3.dll" $sqlite
Copy-One "$VcpkgInstalled\lib\sqlite3.lib" $sqlite

# libogg / libvorbis
Copy-One "$VcpkgInstalled\bin\ogg.dll"          $ogg
Copy-One "$VcpkgInstalled\lib\ogg.lib"          $ogg
Copy-One "$VcpkgInstalled\bin\vorbis.dll"       $ogg
Copy-One "$VcpkgInstalled\lib\vorbis.lib"       $ogg
Copy-One "$VcpkgInstalled\bin\vorbisfile.dll"   $ogg
Copy-One "$VcpkgInstalled\lib\vorbisfile.lib"   $ogg
Copy-One "$VcpkgInstalled\bin\vorbisenc.dll"    $ogg
Copy-One "$VcpkgInstalled\lib\vorbisenc.lib"    $ogg

# zlib (modern vcpkg calls it z.dll / z.lib)
Copy-One "$VcpkgInstalled\bin\z.dll" $zlib
Copy-One "$VcpkgInstalled\lib\z.lib" $zlib

# libwebsockets (+ pthreads runtime; websockets links against pthreads)
Copy-One "$VcpkgInstalled\bin\websockets.dll"  $ws
Copy-One "$VcpkgInstalled\lib\websockets.lib"  $ws
Copy-One "$VcpkgInstalled\bin\pthreadVC3.dll"  $ws
Copy-One "$VcpkgInstalled\lib\pthreadVC3.lib"  $ws

# chipmunk (static lib; header is provided by cocos2d-x itself).
# The overlay port pins 7.0.1 + CP_USE_DOUBLES=0 and builds static, matching
# cocos2d-x's bundled headers and its arm/win32/x64 win10 prebuilts -- so there
# is deliberately no chipmunk.dll to deploy here.
Copy-One "$VcpkgInstalled\lib\chipmunk.lib" $chip

# --- ANGLE (Google's OpenGL ES on top of D3D) for UWP --------------------
# ANGLE.WindowsStore.Servo carries ARM64/x64/x86 UAP binaries; the older
# ANGLE.WindowsStore only had ARM/x64/Win32. We need ARM64 here.
$AngleVersion   = '2.1.20'
$AnglePkgName   = 'angle.windowsstore.servo'
$AngleUrl       = "https://api.nuget.org/v3-flatcontainer/$AnglePkgName/$AngleVersion/$AnglePkgName.$AngleVersion.nupkg"

if (-not $DownloadCacheDir) {
    $DownloadCacheDir = Join-Path (Split-Path $VcpkgInstalled -Parent | Split-Path -Parent) 'downloads'
}
if (-not (Test-Path -LiteralPath $DownloadCacheDir)) {
    New-Item -ItemType Directory -Path $DownloadCacheDir -Force | Out-Null
}
$AngleNupkg    = Join-Path $DownloadCacheDir "$AnglePkgName.$AngleVersion.nupkg"
$AngleExtract  = Join-Path $DownloadCacheDir "$AnglePkgName.$AngleVersion"

if (-not (Test-Path -LiteralPath $AngleNupkg)) {
    Write-Host "downloading $AngleUrl ..."
    Invoke-WebRequest -Uri $AngleUrl -OutFile $AngleNupkg -UseBasicParsing
}
if (-not (Test-Path -LiteralPath $AngleExtract)) {
    Add-Type -AssemblyName 'System.IO.Compression.FileSystem' -ErrorAction SilentlyContinue
    [System.IO.Compression.ZipFile]::ExtractToDirectory($AngleNupkg, $AngleExtract)
}

# Map our lowercase arch names to ANGLE's nupkg subdir names.
$AngleArch = switch ($Arch) {
    'win32' { 'x86' }
    'x64'   { 'x64' }
    'arm64' { 'ARM64' }
    default { $null }
}
if (-not $AngleArch) {
    Write-Warning "ANGLE.WindowsStore.Servo $AngleVersion has no $Arch build; skipping"
} else {
    $angleBinSrc = Join-Path $AngleExtract "bin\UAP\$AngleArch"
    $angleDstBin = "$OutDir\win10-specific\angle\prebuilt\$Arch"
    Copy-One "$angleBinSrc\libEGL.dll"    $angleDstBin
    Copy-One "$angleBinSrc\libEGL.lib"    $angleDstBin
    Copy-One "$angleBinSrc\libGLESv2.dll" $angleDstBin
    Copy-One "$angleBinSrc\libGLESv2.lib" $angleDstBin
    Copy-Tree "$AngleExtract\include" "$OutDir\win10-specific\angle\"
}

Write-Host "== done. Layout populated at $OutDir =="
